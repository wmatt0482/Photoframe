#!/usr/bin/env node
// Bundles ./public into src/assets.generated.js so the Worker can serve the
// web page itself. Wrangler runs this before `dev` and `deploy` (see [build]
// in wrangler.toml). Serving from the Worker keeps the deploy to a single
// script upload.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { extname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.webmanifest': 'application/manifest+json',
};

const root = fileURLToPath(new URL('..', import.meta.url));
const assets = {};
for (const name of readdirSync(join(root, 'public')).sort()) {
  const type = TYPES[extname(name)];
  if (!type) throw new Error(`no content type for public/${name}; add it to TYPES`);
  const body = readFileSync(join(root, 'public', name), 'utf8');
  const etag = `"${createHash('sha256').update(body).digest('hex').slice(0, 16)}"`;
  assets[`/${name}`] = { type, etag, body };
}

writeFileSync(
  join(root, 'src', 'assets.generated.js'),
  `// Generated by tools/embed-assets.mjs. Do not edit.\nexport const ASSETS = ${JSON.stringify(assets)};\n`,
);
console.log(`embedded ${Object.keys(assets).length} files from public/`);
